def main() -> None:
    rows = []
    i = 0
    for intent_id, qas in QA.items():
        for q, points in qas:
            rows.append({"id": f"faq_{i:03d}", "subset": "faq", "split": "test",
                         "text": q,
                         "meta": {"gold_intent": intent_id, "info_points": points}})
            i += 1
    rng.shuffle(rows)                       # 打乱意图顺序
    for j, r in enumerate(rows):            # 重编 id
        r["id"] = f"faq_{j:03d}"
    out = ROOT / "eval" / "datasets" / "faq.jsonl"
    out.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n",
                   encoding="utf-8")
    print(f"faq.jsonl: {len(rows)} rows, 覆盖 {len(QA)} 个 FAQ 意图")


if __name__ == "__main__":
    main()
